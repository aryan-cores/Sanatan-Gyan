// Plays Sanskrit, then (if available) the meaning, back-to-back. If Autoplay is on,
// automatically advances to the next verse and continues the chain.
function playGitaVerseSequence(v, meaningText, hasMeaning, btn, isLastVerse){
  document.querySelectorAll('.listen-btn.playing').forEach(b=>b.classList.remove('playing'));
  btn.classList.add('playing');
  const uS = speak(v.sa, currentLang, 'sanskrit');
  if(!uS) return;
  uS.onend = ()=>{
    if(hasMeaning){
      const uM = speak(meaningText, currentLang, 'meaning');
      if(uM){ uM.onend = ()=> finishGitaSequence(btn, isLastVerse); return; }
    }
    finishGitaSequence(btn, isLastVerse);
  };
}
function finishGitaSequence(btn, isLastVerse){
  btn.classList.remove('playing');
  if(gitaAutoplay && !isLastVerse){
    setTimeout(()=>{
      activeVerseIndex += 1;
      saveGitaProgress();
      renderGita();
      // auto-continue playback on the newly rendered verse
      const newPlayBtn = document.querySelector('.shlok-card .listen-btn-primary');
      if(newPlayBtn) newPlayBtn.click();
    }, 700);
  } else if(gitaAutoplay && isLastVerse){
    gitaAutoplay = false;
  }
}

function renderRamayan() {
  const sidebar = document.getElementById('ramayanSidebar');
  if(!sidebar) return;
  sidebar.innerHTML = '';

  RAMAYAN_DATA.forEach(item => {
    const btn = document.createElement('button');
    btn.className = (item.ch === ramayanActiveCh) ? 'active' : '';
    btn.textContent = item.title[currentLang] || item.title['en'];
    btn.onclick = () => {
      ramayanActiveCh = item.ch;
      ramayanActivePg = 1;
      saveRamayanProgress();
      renderRamayan();
    };
    sidebar.appendChild(btn);
  });

  const currentChData = RAMAYAN_DATA.find(x => x.ch === ramayanActiveCh);
  if(!currentChData) return;
  const currentPgData = currentChData.pages.find(p => p.num === ramayanActivePg) || currentChData.pages[0];

  document.getElementById('ramayanViewTitle').textContent = currentChData.title[currentLang];
  document.getElementById('ramayanViewText').textContent = currentPgData.text[currentLang];
  document.getElementById('ramayanPageIndicator').textContent = `${currentLang==='en'?'Page':'पृष्ठ'} ${ramayanActivePg} / ${currentChData.pages.length}`;
  
  document.getElementById('ramayanPrevBtn').disabled = (ramayanActivePg === 1);
  document.getElementById('ramayanPrevBtn').onclick = () => {
    if (ramayanActivePg > 1) {
      ramayanActivePg--;
      saveRamayanProgress();
      renderRamayan();
    }
  };

  document.getElementById('ramayanNextBtn').disabled = (ramayanActivePg === currentChData.pages.length);
  document.getElementById('ramayanNextBtn').onclick = () => {
    if (ramayanActivePg < currentChData.pages.length) {
      ramayanActivePg++;
      saveRamayanProgress();
      renderRamayan();
    }
  };

  const audioBox = document.getElementById('ramayanAudioBox');
  audioBox.innerHTML = '';
  const audBtn = listenBtn(currentPgData.text[currentLang], currentLang==='en' ? 'Listen to Page Audio' : 'ऑडियो सुनें');
  audioBox.appendChild(audBtn);
}

