// ---------- Voice engine: female voice for Sanskrit shlokas, deep male voice for meanings ----------
let availableVoices = [];
function loadVoices(){ availableVoices = window.speechSynthesis ? window.speechSynthesis.getVoices() : []; }
if('speechSynthesis' in window){
  loadVoices();
  window.speechSynthesis.onvoiceschanged = loadVoices;
}

const MALE_HINTS = ['male','hemant','ravi','prabhat','madhur','rishi','man)','david','daniel','ryan','guy'];
const FEMALE_HINTS = ['female','heera','swara','lekha','kalpana','priya','veena','neerja','woman)','zira','samantha'];

function pickVoice(langCode, gender){
  const prefix = langCode.split('-')[0];
  const matches = availableVoices.filter(v => v.lang && v.lang.toLowerCase().startsWith(prefix));
  if(matches.length === 0) return null;
  const hints = gender === 'male' ? MALE_HINTS : FEMALE_HINTS;

  // Prefer a named match for the requested gender.
  const named = matches.find(v => hints.some(h => v.name.toLowerCase().includes(h)));
  if(named) return named;

  // Otherwise, prefer higher-quality engines (Google's voices are noticeably clearer than
  // default OS voices on most devices) before falling back to whatever is available.
  const google = matches.filter(v => v.name.toLowerCase().includes('google'));
  if(google.length > 1) return gender === 'male' ? google[google.length-1] : google[0];
  if(google.length === 1) return google[0];

  if(matches.length > 1) return gender === 'male' ? matches[1] : matches[0];
  return matches[0];
}

// Tries a list of locale codes in order and returns the first one that has an installed voice.
function pickBestLangCode(candidates){
  for(const code of candidates){
    const prefix = code.split('-')[0];
    if(availableVoices.some(v => v.lang && v.lang.toLowerCase().startsWith(prefix))) return code;
  }
  return candidates[0];
}

/**
 * role: 'sanskrit' -> ALWAYS read with a Hindi/Devanagari-capable voice (hi-IN), regardless of the
 *       UI language, because Devanagari text needs a Devanagari-reading voice to pronounce
 *       correctly. Tuned deep, slow and loud for a clear, resonant recitation tone.
 *       'meaning'  -> read in the selected UI language, deep and clear for easy listening.
 */
function speak(text, lang, role){
  if(!('speechSynthesis' in window)){ alert('Speech not supported in this browser.'); return null; }
  window.speechSynthesis.cancel();
  const u = new SpeechSynthesisUtterance(text);
  u.volume = 1;

  if(role === 'sanskrit'){
    const langCode = 'hi-IN';
    u.lang = langCode;
    const v = pickVoice(langCode, 'female');
    if(v) u.voice = v;
    u.pitch = 0.88;   // deep, resonant recitation tone
    u.rate = 0.75;    // slow enough for each syllable to land clearly
  } else {
    const langCode = lang === 'en'
      ? pickBestLangCode(['en-IN','en-GB','en-US','en'])
      : (speechLang[lang] || 'en-IN');
    u.lang = langCode;
    const v = pickVoice(langCode, 'male');
    if(v) u.voice = v;
    u.pitch = 0.82;
    u.rate = 0.88;
  }
  window.speechSynthesis.speak(u);
  return u;
}

function listenBtn(text, label, role){
  const btn = document.createElement('button');
  btn.className = 'listen-btn';
  btn.innerHTML = `<svg viewBox="0 0 24 24" fill="currentColor"><path d="M8 5v14l11-7z"/></svg> ${label || 'Listen'}`;
  btn.onclick = ()=>{
    document.querySelectorAll('.listen-btn.playing').forEach(b=>b.classList.remove('playing'));
    const u = speak(text, currentLang, role);
    if(u){
      btn.classList.add('playing');
      u.onend = ()=> btn.classList.remove('playing');
    }
  };
  return btn;
}

